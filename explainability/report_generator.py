"""
Patient Report Generator
=========================
Generates comprehensive patient-level health risk explanation reports.
Combines SHAP values, risk factors, and recommendations.
"""


def generate_patient_report(patient_data, risk_score, risk_category, 
                           feature_importance, advice, uncertainty=None):
    """
    Generate a comprehensive patient explanation report.
    
    Args:
        patient_data: dict of patient features
        risk_score: 0-100 risk score
        risk_category: risk category string
        feature_importance: dict of {feature: importance}
        advice: dict from GenAI advisor
        uncertainty: dict from uncertainty estimation
    
    Returns:
        Formatted report string (Markdown)
    """
    
    # Header
    report_lines = [
        "# 🏥 Patient Health Risk Assessment Report",
        "",
        "---",
        "",
        "## Overview",
        "",
        f"| Metric | Value |",
        f"|--------|-------|",
        f"| **Risk Score** | {risk_score}/100 |",
        f"| **Risk Category** | {risk_category} |",
    ]
    
    if uncertainty:
        report_lines.append(f"| **Prediction Confidence** | {uncertainty.get('reliability', 'N/A')} |")
        report_lines.append(f"| **Uncertainty Score** | {uncertainty.get('uncertainty_score', 0):.4f} |")
    
    report_lines.extend(["", "---", ""])
    
    # Patient Data Summary
    report_lines.extend([
        "## Patient Data Summary",
        "",
        "| Feature | Value |",
        "|---------|-------|"
    ])
    
    for key, value in patient_data.items():
        display_name = key.replace("_", " ").title()
        report_lines.append(f"| {display_name} | {value} |")
    
    report_lines.extend(["", "---", ""])
    
    # Top Contributing Factors
    report_lines.extend([
        "## Top Contributing Factors",
        ""
    ])
    
    if feature_importance:
        sorted_features = sorted(feature_importance.items(), key=lambda x: abs(x[1]), reverse=True)[:8]
        for i, (feat, imp) in enumerate(sorted_features, 1):
            bar_len = int(min(abs(imp) * 50, 20))
            bar = "█" * bar_len
            direction = "↑" if imp > 0 else "↓"
            report_lines.append(f"{i}. **{feat.replace('_', ' ').title()}** — {direction} Impact: {abs(imp):.3f} `{bar}`")
    
    report_lines.extend(["", "---", ""])
    
    # Recommendations
    if advice:
        report_lines.extend([
            "## AI-Generated Health Recommendations",
            ""
        ])
        
        if "recommendations" in advice and advice["recommendations"]:
            report_lines.append(advice["recommendations"])
        elif "advice" in advice:
            report_lines.append(advice["advice"][:500])
    
    report_lines.extend(["", "---", ""])
    
    # Disclaimer
    report_lines.extend([
        "## Disclaimer",
        "",
        "*This report is generated by an AI-powered clinical decision support system. "
        "It should not replace professional medical diagnosis or treatment. "
        "Always consult with a qualified healthcare provider for medical advice.*",
        "",
        "---",
        "",
        "*Generated by the Generative Dynamic Health Risk Assessment System (GDHRA)*"
    ])
    
    return "\n".join(report_lines)
